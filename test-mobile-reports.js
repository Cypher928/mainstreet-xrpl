'use strict';
/**
 * test-mobile-reports.js — a report must fit the phone it is read on.
 *
 *   node test-mobile-reports.js
 *   HEADLESS=0 node test-mobile-reports.js      # watch it
 *   SHOTS=1    node test-mobile-reports.js      # write screenshots to ./screenshots
 *
 * THE BUG THIS EXISTS FOR
 * Report tables set `white-space: nowrap` on every column but the first, which
 * is right on a wide screen and right in print — a lease term or a dollar figure
 * must not wrap mid-value. On a 390px phone the Lender Summary's seven-column
 * roster was therefore wider than the viewport, and nothing contained it, so the
 * PAGE scrolled sideways. The toolbar is sticky to the top, not pinned to the
 * left, so it slid off with everything else and took Print / Save PDF and Close
 * with it. A reader could reach the table but not the way out of it.
 *
 * WHAT IS ASSERTED
 * The real Test 2 report bodies — generated by the real builders, not by hand —
 * are injected through the real openReport() and measured in a real browser at
 * 390x844. The page must not scroll horizontally, every wide table must scroll
 * inside its own box, and both toolbar controls must stay on screen at a usable
 * tap size. Desktop is measured too, so a mobile fix cannot quietly regress it.
 *
 * No report logic is exercised or altered here; this is entirely about whether
 * the produced HTML fits.
 */
process.env.TZ = 'America/New_York';

let pw;
try { pw = require('playwright'); }
catch (_) { pw = require('/opt/node22/lib/node_modules/playwright'); }
const { chromium } = pw;

const http = require('http');
const fs   = require('fs');
const path = require('path');
const F    = require('./test-cross-report-fixture.js');

const ROOT     = __dirname;
const PORT     = parseInt(process.env.APP_PORT || '7871', 10);
const HEADLESS = process.env.HEADLESS !== '0';
const SHOTS    = process.env.SHOTS === '1';
const SHOT_DIR = path.join(ROOT, 'screenshots');
const CHROME   = process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';

const MIME = { '.html':'text/html', '.js':'application/javascript', '.css':'text/css',
               '.json':'application/json', '.png':'image/png', '.svg':'image/svg+xml',
               '.mp4':'video/mp4', '.webm':'video/webm', '.woff2':'font/woff2' };

let pass = 0, fail = 0;
const ok  = (m) => { console.log('  \x1b[32m✓\x1b[0m ' + m); pass++; };
const bad = (m, d) => { console.log('  \x1b[31m✗\x1b[0m ' + m + (d ? ' — ' + d : '')); fail++; };
const yes = (m, c, d) => c ? ok(m) : bad(m, d);

function startServer() {
  return new Promise((resolve, reject) => {
    const server = http.createServer((req, res) => {
      const urlPath = req.url.split('?')[0];
      const filePath = path.join(ROOT, urlPath === '/' ? '/index.html' : urlPath);
      fs.readFile(filePath, (err, data) => {
        if (err) { res.writeHead(404); res.end('not found'); return; }
        res.writeHead(200, { 'Content-Type': MIME[path.extname(filePath)] || 'application/octet-stream' });
        res.end(data);
      });
    });
    server.listen(PORT, '127.0.0.1', () => resolve(server));
    server.on('error', reject);
  });
}

// The real Test 2 report bodies. The Lender Summary is the widest (a
// seven-column roster) and the Risk & Disputes report now carries a
// four-column findings table, so both are measured.
const REPORTS = (() => {
  const n = F.auditNarrative();
  return [
    ['Lender Summary',           F.lenderSummary({
      exposure: n.exposure, readiness: n.readiness, camYear: n.camYear, conflicts: n.conflicts })],
    ['Risk & Disputes Report',   F.riskAndDisputes().html],
    ['Audit Exception Summary',  F.exceptionReport().html],
    ['Coverage Gap Report',      F.coverageGap().html],
    ['CAM Reconciliation Summary', F.reconciliationSummary().html],
  ];
})();

(async () => {
  const server  = await startServer();
  const browser = await chromium.launch({ headless: HEADLESS, executablePath: CHROME });

  async function measure(ctxOpts, label) {
    const ctx  = await browser.newContext(ctxOpts);
    const page = await ctx.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(String(e.message)));

    // The Supabase client is fetched from a CDN. This session has no egress, so
    // without a stub the app throws during boot and never signs in. Only the
    // shape the boot path touches is needed; nothing here is measured.
    await page.addInitScript(() => {
      window.supabase = window.supabase || {
        createClient: () => ({
          auth: {
            getSession:            async () => ({ data: { session: null }, error: null }),
            getUser:               async () => ({ data: { user: null }, error: null }),
            onAuthStateChange:     () => ({ data: { subscription: { unsubscribe() {} } } }),
            signInWithPassword:    async () => ({ data: {}, error: null }),
            signOut:               async () => ({ error: null }),
          },
          from: () => ({
            select: function () { return this; }, eq: function () { return this; },
            order:  function () { return this; }, limit: function () { return this; },
            single: async () => ({ data: null, error: null }),
            insert: function () { return this; }, update: function () { return this; },
            delete: function () { return this; },
            then: (r) => r({ data: [], error: null }),
          }),
          storage: { from: () => ({ upload: async () => ({ data: null, error: null }) }) },
        }),
      };
    });

    await page.goto(`http://127.0.0.1:${PORT}/?signin=1`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => typeof window.openReport === 'function', null, { timeout: 45000 });

    // #appContent is display:none until a session exists, and a hidden ancestor
    // gives every descendant a zero-sized rect. An earlier version of this test
    // measured that state and reported every layout assertion as passing on
    // rects of 0x0. Reveal the pane, then assert below that it really laid out —
    // a vacuous pass is worse than a failure.
    await page.evaluate(() => {
      const app = document.getElementById('appContent');
      if (app) app.style.display = 'block';
      // #loginScreen is a sibling of #appContent, so with no session it paints
      // over the report even though the report's own layout is correct. The
      // measurements below were right with it up; the screenshots were not.
      ['loginScreen', 'landingOverlay'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.style.display = 'none';
      });
      document.querySelectorAll('.landing-overlay, #_devRoleSwitcher').forEach(el => { el.style.display = 'none'; });
    });

    const out = [];
    for (const [title, html] of REPORTS) {
      const m = await page.evaluate(([t, h]) => {
        window.openReport(t, h);
        const vw    = window.innerWidth;
        const doc   = document.documentElement;
        const ovl   = document.getElementById('reportOverlay');
        const bar   = document.querySelector('.rpt-toolbar');
        const btns  = [...document.querySelectorAll('.rpt-tool-btn, .rpt-close-btn')];
        const tbls  = [...document.querySelectorAll('#rptBody table.rpt-table')];
        const wraps = [...document.querySelectorAll('#rptBody .rpt-table-scroll')];
        return {
          vw,
          docScrollW:     doc.scrollWidth,
          overlayScrollW: ovl.scrollWidth,
          bodyScrollW:    document.getElementById('rptBody').scrollWidth,
          toolbarH:       bar ? Math.round(bar.getBoundingClientRect().height) : null,
          tables:         tbls.length,
          wrapped:        tbls.filter(t => t.parentElement
                            && t.parentElement.classList.contains('rpt-table-scroll')).length,
          // A wrapper that is itself wider than the viewport has not contained
          // anything; it has just moved the overflow up one level.
          wrapsWithinViewport: wraps.filter(w => w.clientWidth <= vw + 1).length,
          wrapCount:      wraps.length,
          wrapsScrollable: wraps.filter(w => w.scrollWidth > w.clientWidth).length,
          wrapsFocusable:  wraps.filter(w => w.getAttribute('tabindex') === '0').length,
          // titleW is what the compacting is FOR: every pixel the buttons give
          // back is a pixel of report title the reader can actually read.
          // The status bar that collapsed to one character per line. Measure the
          // headline's rendered width, not just that it exists.
          statusHeadlineW: (() => {
            const h = document.querySelector('#rptBody .rpt-status-headline');
            return h ? Math.round(h.getBoundingClientRect().width) : null;
          })(),
          cardTables: [...document.querySelectorAll('#rptBody table.rpt-table--cards')].length,
          // A labelled cell renders its heading through ::before; read it back.
          labelledCells: [...document.querySelectorAll('#rptBody td[data-label]')].length,
          cardLabelShown: (() => {
            const td = document.querySelector('#rptBody .rpt-table--cards tbody td[data-label]');
            if (!td) return null;
            return getComputedStyle(td, '::before').content !== 'none';
          })(),
          // A card that renders in a 180px column of a 390px screen wraps every
          // label one letter per line — the same defect the cards replaced. The
          // suite passed on exactly that state until this measured the card's
          // own width rather than only the table's.
          narrowestCardRow: (() => {
            const rows = [...document.querySelectorAll('#rptBody .rpt-table--cards tbody tr')];
            if (!rows.length) return null;
            return Math.round(Math.min(...rows.map(r => r.getBoundingClientRect().width)));
          })(),
          // The label gutter must fit its shortest real heading on one line.
          labelWraps: (() => {
            const tds = [...document.querySelectorAll('#rptBody .rpt-table--cards tbody td[data-label]')];
            return tds.filter(td => {
              const cs = getComputedStyle(td);
              const col = parseFloat(cs.gridTemplateColumns.split(' ')[0]);
              return isFinite(col) && col < 70;
            }).length;
          })(),
          titleW: (() => {
            const h = document.querySelector('.rpt-toolbar h2');
            return h ? Math.round(h.getBoundingClientRect().width) : 0;
          })(),
          buttons: btns.map(b => {
            const r = b.getBoundingClientRect();
            const long = b.querySelector('.rpt-btn-long');
            return { text: b.textContent.replace(/\s+/g, ' ').trim(),
                     // textContent includes a display:none span, so the visible
                     // label has to be measured, not read.
                     longLabelVisible: !!(long && long.getBoundingClientRect().width > 0),
                     left: Math.round(r.left), right: Math.round(r.right),
                     h: Math.round(r.height), w: Math.round(r.width) };
          }),
        };
      }, [title, html]);
      m.title = title;
      out.push(m);

      if (SHOTS) {
        fs.mkdirSync(SHOT_DIR, { recursive: true });
        const slug = label + '-' + title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
        await page.screenshot({ path: path.join(SHOT_DIR, slug + '.png'), fullPage: false });
        await page.screenshot({ path: path.join(SHOT_DIR, slug + '-full.png'), fullPage: true });
      }
    }
    await ctx.close();
    return { out, errors };
  }

  console.log('\n── Mobile · iPhone-class viewport, 390 x 844 ──');
  const mob = await measure({
    viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true,
    hasTouch: true, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) '
      + 'AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1',
  }, 'mobile');

  mob.out.forEach(m => {
    console.log(`\n  · ${m.title}`);
    // Guard first: everything below measures rectangles, and a hidden ancestor
    // makes every rectangle 0x0, which would pass every assertion vacuously.
    yes('    the report actually laid out (guards against measuring a hidden pane)',
        m.toolbarH > 0 && m.bodyScrollW > 0,
        `toolbar ${m.toolbarH}px, body scrollWidth ${m.bodyScrollW} — the overlay is not visible`);
    yes('    the page does not scroll horizontally',
        m.docScrollW <= m.vw + 1, `document scrollWidth ${m.docScrollW} > viewport ${m.vw}`);
    yes('    the overlay does not scroll horizontally',
        m.overlayScrollW <= m.vw + 1, `overlay scrollWidth ${m.overlayScrollW} > viewport ${m.vw}`);
    if (m.tables > 0) {
      yes(`    all ${m.tables} table(s) are inside a scroll container`,
          m.wrapped === m.tables, `${m.tables - m.wrapped} table(s) left unwrapped`);
      yes('    and every container fits the viewport',
          m.wrapsWithinViewport === m.wrapCount,
          `${m.wrapCount - m.wrapsWithinViewport} container(s) wider than the screen`);
      yes('    a container that clips is reachable by keyboard',
          m.wrapsFocusable === m.wrapCount,
          'a scrollable region has no tabindex, so only a pointer can reach it');
    } else {
      ok('    no tables in this report');
    }
    const print = m.buttons.find(b => /PDF/i.test(b.text));
    const close = m.buttons.find(b => /Close/i.test(b.text));
    yes('    Print / Save PDF is fully on screen',
        !!print && print.left >= 0 && print.right <= m.vw + 1,
        print ? `spans ${print.left}..${print.right} in a ${m.vw}px viewport` : 'button not found');
    yes('    Close is fully on screen',
        !!close && close.left >= 0 && close.right <= m.vw + 1,
        close ? `spans ${close.left}..${close.right} in a ${m.vw}px viewport` : 'button not found');
    yes('    both stay at a 44px tap target',
        !!print && !!close && print.h >= 44 && close.h >= 44,
        `heights ${print && print.h} / ${close && close.h}`);
    // The collapsed-column defect: the headline was the only shrinkable item in
    // a flex row between two flex-shrink:0 siblings, and rendered one character
    // per line. Any width below ~120px on a 390px screen is that failure.
    if (m.statusHeadlineW != null) {
      yes('    the status headline gets a usable column, not one character',
          m.statusHeadlineW >= 150,
          `the headline is ${m.statusHeadlineW}px wide on a ${m.vw}px screen`);
    }
    if (m.cardTables > 0) {
      yes(`    ${m.cardTables} table(s) render as stacked cards`,
          m.labelledCells > 0 && m.cardLabelShown === true,
          `${m.labelledCells} labelled cells, heading rendered: ${m.cardLabelShown}`);
      yes('    and each card uses the full width of the screen',
          m.narrowestCardRow != null && m.narrowestCardRow >= m.vw * 0.8,
          `narrowest card is ${m.narrowestCardRow}px on a ${m.vw}px screen — the table box is still doing table layout`);
      yes('    with a label gutter wide enough not to wrap per letter',
          m.labelWraps === 0,
          `${m.labelWraps} label column(s) narrower than 70px`);
    }
    yes('    the sticky header stays compact',
        m.toolbarH != null && m.toolbarH <= 60,
        `toolbar is ${m.toolbarH}px tall — it is sticky, so every pixel costs report`);
    yes('    the Print button drops its long label to give the title room',
        !!print && print.longLabelVisible === false && print.w <= 80,
        print ? `the print button renders ${print.w}px wide with the long label `
                + `${print.longLabelVisible ? 'shown' : 'hidden'}` : 'button not found');
    yes('    which leaves the title over a third of the bar',
        m.titleW >= m.vw * 0.33,
        `title has only ${m.titleW}px of a ${m.vw}px bar`);
  });
  yes('  no page errors while rendering the reports', mob.errors.length === 0, mob.errors.join(' | '));

  // Belt and braces: the tables are contained, so nothing should reach this
  // rule. It exists for the content types nobody has enumerated yet — a long
  // unbroken vendor name, a future wide block — and its whole job is to keep the
  // sticky toolbar, and therefore Close, on screen. Asserted at source because
  // by design there is nothing left for it to catch.
  yes('  the overlay still refuses to scroll horizontally as a last resort',
      /#reportOverlay\s*\{[^}]*overflow-x:\s*hidden/s.test(
        fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8')),
      'the overlay can scroll sideways again, which takes Close off screen');

  console.log('\n── Desktop · 1280 x 900, unchanged behaviour ──');
  const desk = await measure({ viewport: { width: 1280, height: 900 } }, 'desktop');
  desk.out.forEach(m => {
    yes(`  ${m.title}: the report laid out`, m.toolbarH > 0 && m.bodyScrollW > 0,
        'the overlay is not visible, so nothing below is measured');
    yes(`  ${m.title}: no horizontal page scroll`,
        m.docScrollW <= m.vw + 1, `document scrollWidth ${m.docScrollW} > ${m.vw}`);
    if (m.tables > 0) {
      // Most report tables fit the 880px report column at desktop width. One —
      // the Lender Summary's eight-column Lease Terms Detail — needs about 33px
      // more, and did before this change too; it simply spilled the column
      // instead of scrolling. The requirement is not "never scrolls", which
      // would mean dropping a column a lender asked for. It is that a table
      // needing more room scrolls inside its own box, with nothing lost and the
      // page still still.
      yes(`  ${m.title}: at most one table needs its scroller at desktop width`,
          m.wrapsScrollable <= 1,
          `${m.wrapsScrollable} tables clip on a 1280px screen — a report has grown too wide`);
      yes(`  ${m.title}: every table is still contained`,
          m.wrapped === m.tables && m.wrapsWithinViewport === m.wrapCount,
          'a table is escaping its container on desktop');
    }
  });
  const dPrint = desk.out[0].buttons.find(b => /PDF/i.test(b.text));
  yes('  the full "Print / Save PDF" label is restored on desktop',
      !!dPrint && dPrint.longLabelVisible === true,
      dPrint ? `long label ${dPrint.longLabelVisible ? 'shown' : 'hidden'} at 1280px` : 'button not found');
  yes('  no desktop page errors', desk.errors.length === 0, desk.errors.join(' | '));

  await browser.close();
  server.close();
  console.log(`\n${fail === 0 ? '\x1b[32m' : '\x1b[31m'}RESULT: ${pass} passed, ${fail} failed\x1b[0m`);
  process.exit(fail === 0 ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
