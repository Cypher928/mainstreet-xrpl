const CLEAN = () => {
  ['restoredBanner', '_devRoleSwitcher'].forEach(id => { const e = document.getElementById(id); if (e) e.remove(); });
  document.querySelectorAll('.cc-brief-greet').forEach(el => {
    el.textContent = el.textContent.replace(/,\s*[^,]*$/, '');
  });
};

const report = { plates: [], facts: {} };

async function shoot(page, handle, scene, file, pad = 20) {
  try {
    if (!handle) throw new Error('element not found');
    await handle.scrollIntoViewIfNeeded({ timeout: 4000 }).catch(() => {});
    const undo = await handle.evaluate((el, p) => { const prev = el.style.padding; el.style.padding = p + 'px'; return prev; }, pad);
    await page.waitForTimeout(150);
    await handle.screenshot({ path: path.join(OUT, file), timeout: 9000 });
    await handle.evaluate((el, prev) => { el.style.padding = prev; }, undo);
    const box = await handle.boundingBox();
    report.plates.push({ scene, file, width: box ? Math.round(box.width) : null, height: box ? Math.round(box.height) : null });
    return true;
  } catch (e) {
    report.plates.push({ scene, error: e.message.split('\n')[0] });
    return false;
  }
}

// Find the smallest laid-out element whose text matches — avoids hidden
// ancestors and templates, which time out on screenshot.
const findVisible = (page, re) => page.evaluateHandle(pattern => {
  const rx = new RegExp(pattern, 'i');
  const visible = e => {
    if (!e.offsetParent && getComputedStyle(e).position !== 'fixed') return false;
    const r = e.getBoundingClientRect();
    return r.width > 60 && r.height > 20;
  };
  return Array.from(document.querySelectorAll('div,section,table,li,article'))
    .filter(e => rx.test(e.textContent || '')).filter(visible)
    .sort((a, b) => (a.textContent || '').length - (b.textContent || '').length)[0] || null;
}, re);

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = http.createServer((rq, rs) => {
    let r = decodeURIComponent(rq.url.split('?')[0]); if (r === '/') r = '/index.html';
    fs.readFile(path.join(ROOT, r), (e, d) => {
      if (e) { rs.writeHead(404); rs.end(); return; }
      rs.writeHead(200, { 'Content-Type': MIME[path.extname(r)] || 'application/octet-stream' }); rs.end(d);
    });
  });
  await new Promise(r => srv.listen(PORT, '127.0.0.1', r));

  const browser = await pw.chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const ctx = await browser.newContext({ viewport: { width: 1600, height: 1400 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  await page.addInitScript('window.__TEST_AUTHED=true;');
  await page.addInitScript(SUPABASE_MOCK);
  await page.route('**jsdelivr**', r => r.fulfill({ status: 200, body: '/*x*/' }));
  await page.route('**supabase**', r => {
    const u = r.request().url();
    return u.includes('127.0.0.1') ? r.continue() : r.fulfill({ status: 200, body: '/*x*/' });
  });
  await page.route('**/api/**', r => r.fulfill({ status: 200, contentType: 'application/json', body: '{}' }));

  await page.goto(`http://127.0.0.1:${PORT}/`);
  await page.waitForSelector('#appContent', { state: 'visible', timeout: 15000 }).catch(() => {});
  await page.waitForTimeout(800);
  await page.evaluate(() => { if (typeof loadDemo === 'function') return loadDemo(); });
  await page.waitForTimeout(5000);
  await page.evaluate(CLEAN);

  // ── S3 · Upload surface ──────────────────────────────────────────────────
  await page.evaluate(() => { if (typeof switchWorkspaceTab === 'function') switchWorkspaceTab('property'); });
  await page.waitForTimeout(1000);
  await page.evaluate(CLEAN);
  let el = await page.$('.upload-zone');
  if (!el || !(await el.boundingBox())) el = (await findVisible(page, 'drop.{0,12}file|upload.{0,12}lease')).asElement();
  await shoot(page, el, 'S3', 's3-upload.png');

  // ── S5 · Reconciliation (also S1's cap row) ──────────────────────────────
  await page.evaluate(() => { if (typeof switchWorkspaceTab === 'function') switchWorkspaceTab('cam'); });
  await page.waitForTimeout(600);
  await page.evaluate(() => { if (typeof runAllocation === 'function') return runAllocation(); });
  await page.waitForSelector('.rcs-cap-cell', { timeout: 15000 }).catch(() => {});
  await page.waitForTimeout(500);
  await page.evaluate(CLEAN);
  await shoot(page, await page.$('.rcs-table'), 'S1+S5', 's1-s5-allocation.png');

  // ── S6 · Property Timeline ───────────────────────────────────────────────
  await page.evaluate(() => { if (typeof switchWorkspaceTab === 'function') switchWorkspaceTab('overview'); });
  await page.waitForTimeout(1400);
  await page.evaluate(CLEAN);
  report.facts.timeline = await page.evaluate(() => {
    const s = document.getElementById('propertyActivitySlot');
    const m = s && (s.innerText || '').match(/(\d+)\s+events/i);
    return { events: m ? Number(m[1]) : null };
  });
  await shoot(page, await page.$('#propertyActivitySlot'), 'S6', 's6-timeline.png');

  // ── S7 · Dispute Packet Evidence Index ───────────────────────────────────
  // Resolve through the product's own path first (the Accept button calls this
  // exact function), so the audit fingerprint is genuinely generated.
  report.facts.dispute = await page.evaluate(async () => {
    // Attempt resolution through the product's own path. Note resolveDispute()
    // guards on `d.status !== 'open'` (script.js:12043), and neither seeded
    // dispute is 'open' — they are 'accepted' and 'docs_requested'. So no
    // fingerprint is minted, and the Evidence Index truthfully reads
    // "Not attached". That is the plate we ship; we do not fabricate a hash.
    const open = (typeof disputes !== 'undefined' && disputes)
      ? disputes.filter(x => x && x.status !== 'accepted' && x.status !== 'rejected') : [];
    const d = open[0] || null;
    if (!d) return { resolved: false, why: 'no unresolved dispute in the demo data' };
    const before = { id: d.id, status: d.status, hash: d.hash };
    try { await resolveDispute(d.id, 'accepted'); } catch (e) { return { resolved: false, why: e.message, before }; }
    const after = disputes.find(x => x.id === before.id);
    return { resolved: true, id: before.id, statusBefore: before.status, statusAfter: after && after.status,
             hashGenerated: !!(after && after.hash), hashPrefix: after && after.hash ? String(after.hash).slice(0, 12) : null };
  });
  await page.waitForTimeout(900);
  if (report.facts.dispute && report.facts.dispute.id != null) {
    await page.evaluate(id => { if (typeof generateDisputePacket === 'function') generateDisputePacket(id); }, report.facts.dispute.id);
    await page.waitForTimeout(1200);
    await page.evaluate(CLEAN);
    report.facts.evidenceIndex = await page.evaluate(() => {
      const t = document.querySelector('.rpt-evidence-index');
      if (!t) return null;
      return Array.from(t.querySelectorAll('tbody tr')).map(tr =>
        Array.from(tr.children).map(td => (td.innerText || '').trim()));
    });
    await shoot(page, await page.$('.rpt-evidence-index'), 'S7', 's7-evidence-index.png');
    await page.evaluate(() => { const o = document.getElementById('reportOverlay'); if (o) o.style.display = 'none'; });
  } else {
    report.plates.push({ scene: 'S7', error: 'dispute could not be resolved through the normal flow' });
  }

  // ── S4 · Honest gap + S8 settlement + S9 Command Center ──────────────────
  await page.evaluate(() => { if (typeof showCommandCenter === 'function') showCommandCenter(); });
  await page.waitForTimeout(1500);
  await page.evaluate(CLEAN);
  await shoot(page, (await findVisible(page, 'missing a CAM expense cap')).asElement(), 'S4', 's4-honest-gap.png');
  await shoot(page, (await findVisible(page, 'settled & verified on the XRP Ledger')).asElement(), 'S8', 's8-settlement.png');
  await shoot(page, await page.$('#commandCenter'), 'S9', 's9-command-center.png');

  fs.writeFileSync(path.join(OUT, 'film2-plates.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  await ctx.close(); await browser.close(); srv.close();
})();
