'use strict';
/**
 * Capture the real-UI plates for Film 2 (product film).
 *
 * Same rule as Film 1: every frame carrying a number, a control or a status
 * comes from the shipping product, never from motion graphics. Scenes that the
 * product cannot show are NOT faked — they are reported as errors in the JSON.
 *
 * Three scenes were adapted to the product rather than the reverse
 * (docs/FILM2_FEASIBILITY.md, approved):
 *   S4 — the honest gap is filmed on the Command Center priority card, which is
 *        where it actually renders.
 *   S7 — the Dispute Packet Evidence Index replaces a hash on the card. The
 *        dispute is resolved through resolveDispute() first — the same function
 *        the Accept button calls — so the audit fingerprint is genuinely
 *        generated by the product. If it is not, the plate shows "Not attached"
 *        and that is the truth.
 *
 *   node tools/capture-film2-plates.js [--out DIR]
 */
const http = require('http'), fs = require('fs'), path = require('path');
let pw; try { pw = require('playwright'); }
catch (_) { pw = require('/opt/node22/lib/node_modules/playwright'); }

const ROOT = path.resolve(__dirname, '..');
const PORT = 8823;
const argOut = process.argv.indexOf('--out');
const OUT = argOut > -1 ? process.argv[argOut + 1] : path.join(ROOT, 'assets', 'landing', 'film2');

const MIME = { '.html':'text/html', '.js':'application/javascript', '.css':'text/css',
               '.json':'application/json', '.png':'image/png', '.svg':'image/svg+xml', '.pdf':'application/pdf' };

