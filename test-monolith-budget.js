'use strict';
/**
 * test-monolith-budget.js — script.js does not grow. (Phase 0, P0.0 — the §00 rule.)
 *
 *   node test-monolith-budget.js                   check the tree against the baseline
 *   node test-monolith-budget.js --write-baseline  (re)generate the baseline from the tree
 *
 * THE RULE THIS ENFORCES
 *
 * New functionality lives in dedicated modules. script.js is neither rewritten
 * nor extended: existing code stays where it is unless a slice has a reason to
 * touch it, and when it must, the logic is lifted into a module first and the
 * monolith keeps a thin delegation. No new large function and no new feature
 * system lands in script.js. The goal is not to shrink the monolith by force;
 * it is to stop it growing while its responsibilities steadily leave.
 *
 * That is an implementation rule, not a preference, and a rule nobody can
 * enforce by eye across 31,000 lines. So it is a suite in the regression, and
 * it fails the build. The baseline it measures against is a committed file,
 * generated by THIS program from the tree at the commit that set it — never
 * typed in — so the ceiling and the check cannot disagree about how to count.
 *
 * WHAT IS MEASURED, AND WHY EACH THING
 *
 *   lines                 the whole file. The one number that cannot be argued
 *                         with; every other check is a refinement of it.
 *   functions             top-level `function name(` declarations at column 0.
 *                         A new feature system announces itself as new
 *                         functions; a delegation is one.
 *   new function bodies   a function whose name is not in the baseline may be
 *                         at most 12 body lines — a delegation fits, a feature
 *                         does not. The body runs from the declaration to the
 *                         first `}` at column 0, which is how this file closes
 *                         every top-level function.
 *   new function names    a new function named for a NEW subject area — the
 *                         acquisition work, documents, provisions, families,
 *                         attention, events, organisations, lifecycle — fails
 *                         regardless of length. Those names have homes in the
 *                         modules the plan names, and a 12-line stub in the
 *                         monolith is how a module starts growing in the wrong
 *                         file.
 *   index.html inline JS  the same rule for the inline <script> blocks. New
 *                         markup carries ids and data- attributes that modules
 *                         bind to; it does not carry logic.
 *
 * THE RATCHET
 *
 * A slice that lifts code out lowers the numbers, and re-runs --write-baseline
 * in the same commit so the ceiling follows it down. The writer refuses to
 * raise any number, and the check compares the working-tree baseline with the
 * one committed at HEAD and refuses a baseline that went up. So the ceiling
 * only ever moves in one direction, and moving it is a visible act in a diff.
 *
 * WHAT IT DOES NOT DO
 *
 * It does not judge existing code. Every function already in script.js at the
 * baseline commit is grandfathered by name; only growth is refused. It says
 * nothing about modules, which are where the work is meant to go.
 */

const fs   = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT          = __dirname;
const SCRIPT        = path.join(ROOT, 'script.js');
const INDEX         = path.join(ROOT, 'index.html');
const BASELINE_PATH = path.join(ROOT, 'test-support', 'monolith-baseline.json');
const BASELINE_REL  = 'test-support/monolith-baseline.json';

/** A delegation fits in this; a feature does not. */
const MAX_NEW_BODY_LINES = 12;

/**
 * New subject areas. A new top-level function in script.js whose name matches
 * belongs in a module, whatever its length. Word-ish matching is deliberate:
 * `_acqOpen`, `classifyDocument`, `renderProvisionRow`, `stageBadge` all fail.
 */
const SUBJECT_RE = /acq|acquisition|document|classif|provision|family|attention|event|organi[sz]ation|lifecycle|stage/i;

// ── Measurement (pure; exported for the self-test below) ────────────────────

/** wc -l semantics: the number of newline characters. */
function countLines(src) {
  let n = 0;
  for (let i = 0; i < src.length; i++) if (src.charCodeAt(i) === 10) n++;
  return n;
}

/**
 * Top-level function declarations and their body lengths.
 *
 * A declaration is `function name(` or `async function name(` starting at
 * column 0. Its body ends at the first subsequent line that is exactly `}` —
 * the closing brace at column 0 that every top-level function in script.js
 * ends with. A declaration with no such close before the next declaration is
 * reported with an Infinite body, which fails the length check rather than
 * slipping under it.
 */
function topLevelFunctions(src) {
  const lines = src.split('\n');
  const out = [];
  const DECL = /^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(/;
  for (let i = 0; i < lines.length; i++) {
    const m = DECL.exec(lines[i]);
    if (!m) continue;
    let close = -1;
    for (let j = i + 1; j < lines.length; j++) {
      if (lines[j] === '}') { close = j; break; }
      if (DECL.test(lines[j])) break;              // ran into the next declaration
    }
    out.push({ name: m[1], line: i + 1, bodyLines: close === -1 ? Infinity : close - i - 1 });
  }
  return out;
}

/**
 * Lines inside inline <script> blocks that carry logic: no `src`, and no
 * non-JavaScript `type` (application/ld+json is data). Counted strictly
 * between the open and close tags.
 */
function inlineScriptLines(html) {
  const lines = html.split('\n');
  let total = 0, open = -1;
  const OPEN = /<script\b([^>]*)>/i, CLOSE = /<\/script>/i;
  for (let i = 0; i < lines.length; i++) {
    if (open === -1) {
      const m = OPEN.exec(lines[i]);
      if (!m) continue;
      const attrs = m[1] || '';
      if (/\bsrc\s*=/i.test(attrs)) continue;
      const type = (/\btype\s*=\s*["']([^"']+)["']/i.exec(attrs) || [])[1];
      if (type && !/javascript|module|ecmascript/i.test(type)) continue;
      if (CLOSE.test(lines[i])) continue;           // opened and closed on one line: no lines inside
      open = i;
    } else if (CLOSE.test(lines[i])) {
      total += i - open - 1;
      open = -1;
    }
  }
  return total;
}

function measure() {
  const script = fs.readFileSync(SCRIPT, 'utf8');
  const html   = fs.readFileSync(INDEX, 'utf8');
  const fns    = topLevelFunctions(script);
  return {
    lines:                  countLines(script),
    functions:              fns.length,
    names:                  fns.map(f => f.name),
    indexInlineScriptLines: inlineScriptLines(html),
    _fns: fns,
  };
}

function gitShort() {
  try { return execSync('git rev-parse --short HEAD', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); }
  catch (_) { return 'unknown'; }
}

/** The baseline as committed at HEAD, or null when git cannot say (a copy with no .git). */
function committedBaseline() {
  try {
    const txt = execSync('git show HEAD:' + BASELINE_REL, { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString();
    return JSON.parse(txt);
  } catch (_) { return null; }
}

// ── --write-baseline ────────────────────────────────────────────────────────

if (process.argv.includes('--write-baseline')) {
  const m = measure();
  const next = {
    _what:    'The monolith ceiling. Generated by test-monolith-budget.js --write-baseline; never edited by hand. It only goes down.',
    commit:   gitShort(),
    setAt:    new Date().toISOString(),
    lines:    m.lines,
    functions: m.functions,
    indexInlineScriptLines: m.indexInlineScriptLines,
    names:    m.names.slice().sort(),
  };
  if (fs.existsSync(BASELINE_PATH)) {
    const prev = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8'));
    const up = [];
    if (next.lines > prev.lines) up.push(`lines ${prev.lines} → ${next.lines}`);
    if (next.functions > prev.functions) up.push(`functions ${prev.functions} → ${next.functions}`);
    if (next.indexInlineScriptLines > prev.indexInlineScriptLines) up.push(`index.html inline script lines ${prev.indexInlineScriptLines} → ${next.indexInlineScriptLines}`);
    if (up.length) {
      console.error('\x1b[31mREFUSED: the ceiling only goes down. This tree is above the current baseline:\x1b[0m\n  ' + up.join('\n  ') +
        '\n  Lift the code out; do not raise the ceiling.');
      process.exit(1);
    }
  }
  fs.mkdirSync(path.dirname(BASELINE_PATH), { recursive: true });
  fs.writeFileSync(BASELINE_PATH, JSON.stringify(next, null, 2) + '\n');
  console.log(`baseline written: ${BASELINE_REL} @ ${next.commit} — ${next.lines} lines · ${next.functions} functions · ${next.indexInlineScriptLines} inline index.html lines`);
  process.exit(0);
}

// ── Check ───────────────────────────────────────────────────────────────────

let pass = 0, fail = 0;
const failures = [];
function t(name, fn) {
  try { fn(); pass++; console.log(`  \x1b[32m✓\x1b[0m ${name}`); }
  catch (e) { fail++; failures.push(`${name}: ${e.message}`); console.log(`  \x1b[31m✗\x1b[0m ${name}\n      → ${e.message}`); }
}
const ok = (c, m) => { if (!c) throw new Error(m || 'expected truthy'); };
const eq = (a, b, m) => { if (a !== b) throw new Error(`${m || ''} expected ${JSON.stringify(b)}, got ${JSON.stringify(a)}`); };

console.log('\n══ Monolith budget — script.js does not grow (§00) ══');

// ── Self-test: the measurer must bite before it is trusted ──────────────────
console.log('\n── The measurer itself ──');
t('counts lines the way wc -l does', () => {
  eq(countLines('a\nb\nc\n'), 3); eq(countLines('a\nb'), 1); eq(countLines(''), 0);
});
t('finds top-level declarations and measures their bodies to the column-0 brace', () => {
  const src = [
    'function one() {', '  return 1;', '}',                         // body 1
    'async function two(a, b) {', '  a;', '  b;', '  return a;', '}', // body 3
    '  function nested() { return 0; }',                            // indented: not top-level
    'const f = function three() {};',                               // expression: not a declaration
    'function four() {', '  return 4;',                             // never closes at column 0
  ].join('\n');
  const fns = topLevelFunctions(src);
  eq(fns.map(f => f.name).join(','), 'one,two,four');
  eq(fns[0].bodyLines, 1); eq(fns[1].bodyLines, 3); eq(fns[2].bodyLines, Infinity, 'an unclosed body is Infinite, never 0');
});
t('counts inline <script> logic and ignores src and data blocks', () => {
  const html = [
    '<script>', 'a', 'b', '</script>',                                   // 2
    '<script src="x.js"></script>',                                     // 0
    '<script type="application/ld+json">', '{}', '</script>',           // 0 (data)
    '<script type="module">', 'c', '</script>',                          // 1
    '<script>x()</script>',                                             // 0 (one line, nothing inside)
  ].join('\n');
  eq(inlineScriptLines(html), 3);
});

// ── The baseline ────────────────────────────────────────────────────────────
console.log('\n── The baseline ──');
let base = null;
t(`${BASELINE_REL} exists and is complete`, () => {
  ok(fs.existsSync(BASELINE_PATH), 'missing — run: node test-monolith-budget.js --write-baseline');
  base = JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8'));
  for (const k of ['commit', 'lines', 'functions', 'indexInlineScriptLines', 'names']) ok(k in base, `baseline lacks "${k}"`);
  ok(Array.isArray(base.names), 'names is not an array');
  eq(base.names.length, base.functions, 'names[] and functions disagree —');
});
if (!base) { finish(); }

const cur = measure();
const baseNames = new Set(base.names);
console.log(`\n  baseline @ ${base.commit}: ${base.lines} lines · ${base.functions} functions · ${base.indexInlineScriptLines} inline index.html lines`);
console.log(`  this tree:           ${cur.lines} lines · ${cur.functions} functions · ${cur.indexInlineScriptLines} inline index.html lines`);

// ── The ceiling ─────────────────────────────────────────────────────────────
console.log('\n── The ceiling ──');
t(`script.js has not grown in lines (${cur.lines} ≤ ${base.lines})`, () => {
  ok(cur.lines <= base.lines, `script.js is ${cur.lines - base.lines} line(s) over the ceiling. New logic belongs in a module.`);
});
t(`script.js has not grown in top-level functions (${cur.functions} ≤ ${base.functions})`, () => {
  ok(cur.functions <= base.functions, `${cur.functions - base.functions} more top-level function(s) than the ceiling. A delegation replaces an existing function; it does not add one.`);
});
t(`index.html inline script logic has not grown (${cur.indexInlineScriptLines} ≤ ${base.indexInlineScriptLines})`, () => {
  ok(cur.indexInlineScriptLines <= base.indexInlineScriptLines, `${cur.indexInlineScriptLines - base.indexInlineScriptLines} more inline script line(s) than the ceiling. Markup carries ids and data- attributes; modules carry logic.`);
});

// ── New functions ───────────────────────────────────────────────────────────
console.log('\n── Functions not in the baseline ──');
const fresh = cur._fns.filter(f => !baseNames.has(f.name));
console.log(`  ${fresh.length} new top-level function name(s)` + (fresh.length ? ': ' + fresh.map(f => f.name).join(', ') : ''));
t(`every new function is a delegation — at most ${MAX_NEW_BODY_LINES} body lines`, () => {
  const big = fresh.filter(f => f.bodyLines > MAX_NEW_BODY_LINES);
  ok(big.length === 0, big.map(f => `${f.name} (line ${f.line}, ${f.bodyLines === Infinity ? 'unclosed' : f.bodyLines + ' lines'})`).join('; ') +
     ' — lift the body into a module and leave a one-expression delegation.');
});
t('no new function is named for a new subject area', () => {
  const named = fresh.filter(f => SUBJECT_RE.test(f.name));
  ok(named.length === 0, named.map(f => `${f.name} (line ${f.line})`).join('; ') +
     ' — acquisition, document, provision, family, attention, event, organisation, lifecycle and stage code has a module; it does not start in script.js.');
});

// ── The ratchet ─────────────────────────────────────────────────────────────
console.log('\n── The ratchet ──');
t('the working-tree baseline is not above the one committed at HEAD', () => {
  const head = committedBaseline();
  if (!head) { console.log('      (no committed baseline reachable — a first commit, or a copy without .git; nothing to ratchet against)'); return; }
  const up = [];
  if (base.lines > head.lines) up.push(`lines ${head.lines} → ${base.lines}`);
  if (base.functions > head.functions) up.push(`functions ${head.functions} → ${base.functions}`);
  if (base.indexInlineScriptLines > head.indexInlineScriptLines) up.push(`inline index.html lines ${head.indexInlineScriptLines} → ${base.indexInlineScriptLines}`);
  ok(up.length === 0, 'the ceiling was raised: ' + up.join(', ') + '. It only goes down.');
});

finish();

function finish() {
  console.log('\n' + '─'.repeat(58));
  if (fail) {
    console.log(`\x1b[31mRESULT: ${pass} passed, ${fail} failed\x1b[0m`);
    failures.forEach(f => console.log(`  · ${f}`));
    process.exit(1);
  }
  console.log(`\x1b[32mRESULT: ${pass} passed, 0 failed\x1b[0m`);
  process.exit(0);
}

module.exports = { countLines, topLevelFunctions, inlineScriptLines, MAX_NEW_BODY_LINES, SUBJECT_RE };
